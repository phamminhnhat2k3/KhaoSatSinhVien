import { expect, test } from "@playwright/test";
import { PrismaClient } from "@prisma/client";
import { hash } from "argon2";
import { randomUUID } from "node:crypto";

test("rà soát ghi danh, CSV an toàn và khóa quyền API của phiên cũ", async ({ page, browser }) => {
  test.skip(!process.env.ISOLATED_FEATURE_DB, "Chỉ chạy trong database nghiệm thu riêng.");
  test.setTimeout(120000);
  const db = new PrismaClient(), tag = `CHECK-${randomUUID().slice(0, 6)}`, password = randomUUID();
  const context = await browser.newContext();
  try {
    expect(new URL(process.env.DATABASE_URL!).pathname).toBe(`/${process.env.ISOLATED_FEATURE_DB}`);
    const passwordHash = await hash(password);
    const faculty = await db.faculty.create({ data: { code: tag, name: tag } });
    const other = await db.faculty.create({ data: { code: `${tag}-other`, name: `${tag} Other` } });
    const home = await db.academicClass.create({ data: { code: tag, name: tag, facultyId: faculty.id, educationSystem: "REGULAR" } });
    const otherHome = await db.academicClass.create({ data: { code: `${tag}-other`, name: `${tag} Other`, facultyId: other.id } });
    const term = await db.semester.create({ data: { name: tag, startsAt: new Date(Date.now() - 86400000), endsAt: new Date(Date.now() + 86400000) } });
    const course = await db.course.create({ data: { code: tag, name: tag, facultyId: faculty.id } });
    const outside = await db.course.create({ data: { code: `${tag}-other`, name: `${tag} Other`, facultyId: other.id } });
    const group = await db.courseClass.create({ data: { code: tag, courseId: course.id, semesterId: term.id } });
    const alternate = await db.courseClass.create({ data: { code: `${tag}-alt`, courseId: course.id, semesterId: term.id } });
    const wrongSystem = await db.courseClass.create({ data: { code: `${tag}-part`, courseId: course.id, semesterId: term.id, educationSystem: "PART_TIME" } });
    const foreign = await db.courseClass.create({ data: { code: `${tag}-foreign`, courseId: outside.id, semesterId: term.id } });
    await db.classStudyAssignment.create({ data: { academicClassId: home.id, classId: group.id } });
    const admin = await db.user.create({ data: { name: tag, email: `${tag}-admin@example.invalid`, passwordHash, roles: { create: { role: "ADMIN" } } } });
    await page.goto("/login");
    await page.getByLabel("Email", { exact: true }).fill(admin.email);
    await page.getByLabel("Mật khẩu", { exact: true }).fill(password);
    await page.getByRole("button", { name: "Đăng nhập", exact: true }).click();
    await page.waitForURL("**/admin");
    await page.goto("/admin/students/new");
    await page.getByLabel("Họ tên", { exact: true }).fill(tag);
    await page.getByLabel("Mã sinh viên", { exact: true }).fill(tag);
    const email = `${tag}-student@example.invalid`;
    await page.getByLabel("Email", { exact: true }).fill(email);
    await page.getByLabel("Mật khẩu khởi tạo", { exact: true }).fill(password);
    await page.getByRole("combobox", { name: "Khoa", exact: true }).selectOption(faculty.id);
    await page.getByRole("combobox", { name: "Lớp hành chính", exact: true }).selectOption(home.id);
    await expect(page.locator(`input[value="${foreign.id}"]`)).toHaveCount(0);
    await expect(page.locator(`input[value="${wrongSystem.id}"]`)).toHaveCount(0);
    const form = page.locator("form").filter({ has: page.getByRole("button", { name: "Tạo sinh viên", exact: true }) });
    await form.evaluate((el, id) => { const field = document.createElement("input"); field.type = "hidden"; field.name = "courseClassIds"; field.value = id; field.id = "forged-enrollment"; el.append(field); }, foreign.id);
    await page.getByRole("button", { name: "Tạo sinh viên", exact: true }).click();
    await expect(form.getByRole("alert")).toContainText("đúng khoa");
    expect(await db.user.count({ where: { email } })).toBe(0);
    await page.locator("#forged-enrollment").evaluate(el => el.remove());
    await page.locator(`input[value="${group.id}"]`).check();
    await page.getByRole("button", { name: "Tạo sinh viên", exact: true }).click();
    await page.waitForURL(/\/admin\/users\?/);
    const student = await db.studentProfile.findUniqueOrThrow({ where: { studentCode: tag }, include: { user: true } });
    await page.goto(`/admin/students/${student.id}`);
    const enroll = page.locator("form").filter({ has: page.getByRole("button", { name: "Bổ sung lớp học phần", exact: true }) });
    const previousSemester = await enroll.getByRole("combobox", { name: "Học kỳ ghi danh", exact: true }).inputValue();
    await enroll.getByRole("combobox", { name: "Học kỳ ghi danh", exact: true }).selectOption(term.id);
    await enroll.locator(`input[value="${alternate.id}"]`).check();
    await enroll.getByRole("button", { name: "Bổ sung lớp học phần", exact: true }).click();
    await expect(enroll.getByRole("status")).toContainText("Mỗi môn chỉ chọn một");
    expect(await db.enrollment.count({ where: { studentId: student.id, classId: alternate.id } })).toBe(0);
    await enroll.locator(`input[value="${alternate.id}"]`).uncheck();
    await enroll.getByRole("combobox", { name: "Học kỳ ghi danh", exact: true }).selectOption(previousSemester);
    const placement = page.locator("form").filter({ has: page.getByRole("button", { name: "Lưu khoa/lớp", exact: true }) });
    await placement.getByRole("combobox", { name: "Lớp hành chính", exact: true }).selectOption(otherHome.id);
    await placement.getByRole("button", { name: "Lưu khoa/lớp", exact: true }).click();
    await expect(placement.getByRole("status")).toContainText("Không thể chuyển lớp");
    expect((await db.studentProfile.findUniqueOrThrow({ where: { id: student.id } })).academicClassId).toBe(home.id);
    await page.goto("/admin/academic");
    const homeRow = page.locator("tbody tr").filter({ has: page.getByRole("dialog", { name: `Sửa lớp hành chính ${tag}`, exact: true, includeHidden: true }) });
    await homeRow.getByRole("button", { name: "Sửa nhanh", exact: true }).click();
    const editHome = page.getByRole("dialog", { name: `Sửa lớp hành chính ${tag}`, exact: true });
    await editHome.getByRole("combobox", { name: "Hệ học", exact: true }).selectOption("PART_TIME");
    await editHome.getByRole("button", { name: "Lưu lớp hành chính", exact: true }).click();
    await expect(editHome.getByRole("status")).toContainText("Không thể đổi hệ học");
    expect((await db.academicClass.findUniqueOrThrow({ where: { id: home.id } })).educationSystem).toBe("REGULAR");

    const template = await db.surveyTemplate.create({ data: { title: tag, questions: { create: { content: tag, type: "TEXT", required: false, position: 1 } } }, include: { questions: true } });
    const campaign = await db.surveyCampaign.create({ data: { title: tag, scope: "FACULTY", facultyId: faculty.id, semesterId: term.id, status: "PUBLISHED", templateId: template.id, startsAt: new Date(Date.now() - 86400000), endsAt: new Date(Date.now() + 86400000), participations: { create: { studentId: student.id } } } });
    const studentPage = await context.newPage();
    await studentPage.goto(new URL("/login", page.url()).href);
    await studentPage.getByLabel("Email", { exact: true }).fill(email);
    await studentPage.getByLabel("Mật khẩu", { exact: true }).fill(password);
    await studentPage.getByRole("button", { name: "Đăng nhập", exact: true }).click();
    await studentPage.waitForURL("**/student");
    const origin = new URL(studentPage.url()).origin;
    expect((await context.request.get(`${origin}/api/surveys/assigned`)).status()).toBe(200);
    await db.user.update({ where: { id: student.userId }, data: { active: false } });
    expect((await context.request.get(`${origin}/api/me`)).status()).toBe(401);
    expect((await context.request.get(`${origin}/api/surveys/assigned`)).status()).toBe(403);
    expect((await context.request.get(`${origin}/api/surveys/${campaign.id}`)).status()).toBe(403);
    expect((await context.request.post(`${origin}/api/surveys/${campaign.id}/submit`, { data: {} })).status()).toBe(403);
    await studentPage.goto(`${origin}/login`);
    await expect(studentPage.getByRole("button", { name: "Đăng nhập", exact: true })).toBeVisible();
    const closed = await db.surveyCampaign.create({ data: { title: `${tag}-csv`, scope: "FACULTY", facultyId: faculty.id, status: "CLOSED", templateId: template.id, startsAt: new Date(Date.now() - 86400000), endsAt: new Date(), submissions: { create: ["=1+1", "Nội dung bình thường"].map(value => ({ answers: { create: { questionId: template.questions[0].id, value } } })) } } });
    const csv = await page.request.get(`/api/reports/campaigns/${closed.id}/export`);
    expect(csv.ok()).toBe(true); expect(csv.headers()["cache-control"]).toBe("private, no-store");
    expect(await csv.text()).toContain("\"'=1+1");
  } finally {
    await context.close();
    try {
      await db.surveyCampaign.deleteMany({ where: { title: { startsWith: tag } } });
      await db.surveyTemplate.deleteMany({ where: { title: tag } });
      await db.auditLog.deleteMany({ where: { actor: { email: { startsWith: `${tag}-` } } } });
      await db.user.deleteMany({ where: { email: { startsWith: `${tag}-` } } });
      await db.classStudyAssignment.deleteMany({ where: { academicClass: { code: tag } } });
      await db.courseClass.deleteMany({ where: { code: { startsWith: tag } } });
      await db.course.deleteMany({ where: { code: { startsWith: tag } } });
      await db.academicClass.deleteMany({ where: { code: { startsWith: tag } } });
      await db.faculty.deleteMany({ where: { code: { startsWith: tag } } });
      await db.semester.deleteMany({ where: { name: tag } });
    } finally { await db.$disconnect(); }
  }
});
