import { expect, test } from "@playwright/test";
import { PrismaClient } from "@prisma/client";
import { randomUUID } from "node:crypto";
import { hash } from "argon2";
test("quản lý người dùng, sửa/xóa khoa và thông báo trượt đúng phạm vi", async ({ page }) => {
  test.skip(!process.env.ISOLATED_FEATURE_DB, "Chỉ chạy với database nghiệm thu riêng.");
  test.setTimeout(120000);
  const db = new PrismaClient(), tag = `MAN-${randomUUID().slice(0,6)}`, password = randomUUID();
  const fixtureUserIds: string[] = [];
  try {
    const faculty = await db.faculty.create({ data: { code: tag, name: `${tag} Khoa` } });
    const home = await db.academicClass.create({ data: { code: tag, name: tag, facultyId: faculty.id } });
    const passwordHash = await hash(password);
    const admin = await db.user.create({ data: { name: `${tag} Admin`, email: `${tag}-a@example.invalid`, passwordHash, roles: { create: { role: "ADMIN" } } } });
    const teacher = await db.user.create({ data: { name: `${tag} Teacher`, email: `${tag}-t@example.invalid`, passwordHash, roles: { create: { role: "LECTURER" } }, lecturer: { create: { lecturerCode: tag, facultyId: faculty.id } } } });
    const course = await db.course.create({data:{code:tag,name:`${tag} Vẽ kỹ thuật`,facultyId:faculty.id,lecturers:{connect:{userId:teacher.id}}}});
    fixtureUserIds.push(admin.id, teacher.id);
    const students = [];
    for (let i=0;i<2;i++) students.push(await db.user.create({ data: { name: `${tag} Student ${i}`, email: `${tag}-s${i}@example.invalid`, passwordHash, roles: { create: { role: "STUDENT" } }, student: { create: { studentCode: `${tag}-${i}`, academicClassId: home.id } } }, include: { student: true } }));
    const template = await db.surveyTemplate.create({ data: { title: tag } });
    fixtureUserIds.push(...students.map(s => s.id));
    await db.surveyCampaign.create({ data: { title: tag, templateId: template.id, scope: "FACULTY", facultyId: faculty.id, startsAt: new Date(), endsAt: new Date(), participations: { create: { studentId: students[1].student!.id } } } });
    const privateNotice = await db.notification.create({ data: { userId: teacher.id, title: `${tag} riêng tư`, body: "Chỉ giảng viên được đọc", href: "/profile" } });
    await page.goto("/login");
    await page.getByLabel("Email", { exact: true }).fill(admin.email);
    await page.getByLabel("Mật khẩu", { exact: true }).fill(password);
    await page.getByRole("button", { name: "Đăng nhập", exact: true }).click();
    await expect(page).toHaveURL(/\/admin$/);
    const hydrationErrors:string[]=[];
    const collect=(error:Error)=>hydrationErrors.push(error.message);
    page.on("pageerror",collect);
    page.on("console",message=>{if(message.type()==="error"&&/hydration|cannot be a descendant|validateDOMNesting/i.test(message.text()))hydrationErrors.push(message.text());});
    await page.goto("/admin/lecturers");
    const lecturerCard=page.locator("details.card").filter({has:page.getByRole("button",{name:`${tag} Teacher`,exact:true})});
    await lecturerCard.locator("summary").press("Enter");
    await lecturerCard.getByRole("button",{name:course.name,exact:true}).click();
    const courseInfo=page.getByRole("dialog",{name:`Thông tin ${course.name}`,exact:true});
    await expect(courseInfo).toBeVisible();
    expect(await courseInfo.evaluate(el=>el.parentElement===document.body)).toBe(true);
    await expect(courseInfo).toContainText(course.name);
    await page.keyboard.press("Escape"); await expect(courseInfo).toHaveCount(0);
    await lecturerCard.getByRole("button",{name:course.name,exact:true}).click();
    await courseInfo.getByRole("button",{name:"Đóng thông tin",exact:true}).click(); await expect(courseInfo).toHaveCount(0);
    expect(hydrationErrors).toEqual([]); page.off("pageerror",collect);
    await page.goto("/admin");
    const campaignFilters = page.getByRole("navigation", { name: "Lọc đợt khảo sát", exact: true });
    await campaignFilters.getByRole("link", { name: /^Bản nháp/ }).click();
    await expect(page.locator("section.question").getByRole("heading", { name: tag, exact: true })).toBeVisible();
    await campaignFilters.getByRole("link", { name: /^Đang mở/ }).click();
    await expect(page.locator("section.question").getByRole("heading", { name: tag, exact: true })).toHaveCount(0);
    await campaignFilters.getByRole("link", { name: /^Tất cả/ }).click();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: ".playwright-cli/admin-home-desktop.png", fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: ".playwright-cli/admin-home-mobile.png", fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator("main").getByRole("link", { name: "Tất cả người dùng", exact: true }).click();
    await expect(page).toHaveURL(/\/admin\/users$/);
    await page.getByLabel("Tìm người dùng", { exact: true }).fill(tag);
    await page.getByRole("button", { name: "Lọc người dùng", exact: true }).click();
    await expect(page.getByRole("heading", { name: "4 người dùng phù hợp", exact: true })).toBeVisible();
    await expect(page.locator("main tbody .role-tag--student")).toHaveCount(2);
    await expect(page.locator("main tbody .role-tag--lecturer")).toHaveCount(1);
    await expect(page.locator("main tbody .role-tag--admin")).toHaveCount(1);
    await expect(page.locator(".sidebar .role-tag--admin")).toHaveText("Quản trị viên");
    await expect(page.getByRole("img", { name: "Sinh viên: 2, Giảng viên: 1, Trưởng khoa: 0, Quản trị viên: 1, Chưa có vai trò: 0", exact: true })).toBeVisible();
    await page.screenshot({ path: ".playwright-cli/user-dashboard-desktop.png", fullPage: true });
    await page.getByRole("combobox", { name: "Vai trò", exact: true }).selectOption("LECTURER");
    await page.getByRole("button", { name: "Lọc người dùng", exact: true }).click();
    await expect(page.getByRole("heading", { name: "1 người dùng phù hợp", exact: true })).toBeVisible();
    await page.getByRole("button", { name: `${tag} Teacher`, exact: true }).click();
    const info = page.getByRole("dialog", { name: `Thông tin ${tag} Teacher`, exact: true });
    await expect(info.getByText(teacher.email, { exact: true })).toBeVisible();
    await expect(page).toHaveURL(/\/admin\/users/);
    for (const width of [1440, 390]) {
      await page.setViewportSize({ width, height: 900 });
      const box = await info.boundingBox();
      expect(box).not.toBeNull();
      expect(Math.abs(box!.x + box!.width / 2 - width / 2)).toBeLessThan(3);
      expect(Math.abs(box!.y + box!.height / 2 - 450)).toBeLessThan(3);
    }
    await page.setViewportSize({ width: 1440, height: 1000 });
    await expect(info.getByRole("button", { name: "Sao chép email", exact: true })).toBeVisible();
    await page.screenshot({ path: ".playwright-cli/entity-centered-desktop.png" });
    await info.getByRole("button", { name: "Đóng thông tin", exact: true }).click();
    await page.getByRole("button", { name: "Sửa nhanh", exact: true }).click();
    let dialog = page.getByRole("dialog");
    await expect(dialog.getByLabel("Họ tên", { exact: true })).toHaveAttribute("readonly", "");
    await expect(dialog.getByLabel("Email", { exact: true })).toHaveAttribute("readonly", "");
    await dialog.locator('input[name="name"]').evaluate((el: HTMLInputElement) => { el.value = "Tên giả mạo"; });
    await dialog.locator('input[name="phone"]').evaluate((el: HTMLInputElement) => { el.value = "0900000000"; });
    await dialog.getByLabel("Cấp quyền Trưởng khoa").check();
    await dialog.getByRole("button", { name: "Lưu giảng viên", exact: true }).click();
    await expect(dialog.getByRole("status")).toHaveText("Đã lưu giảng viên.");
    expect((await db.user.findUniqueOrThrow({ where: { id: teacher.id }, include: { roles: true } })).roles.map(r => r.role)).toContain("DEAN");
    expect((await db.user.findUniqueOrThrow({ where: { id: teacher.id } })).name).toBe(`${tag} Teacher`);
    expect((await db.user.findUniqueOrThrow({ where: { id: teacher.id } })).phone).toBe("");
    await dialog.getByRole("button", { name: "Đóng chỉnh sửa" }).click();
    await page.goto(`/admin/users?q=${students[0].email}`);
    await page.getByRole("button", { name: "Sửa nhanh", exact: true }).click();
    dialog = page.getByRole("dialog");
    await expect(dialog.getByLabel("Họ tên", { exact: true })).toHaveAttribute("readonly", "");
    await dialog.locator('input[name="name"]').evaluate((el: HTMLInputElement) => { el.value = "Tên giả mạo"; });
    await dialog.locator('input[name="phone"]').evaluate((el: HTMLInputElement) => { el.value = "0911111111"; });
    await dialog.getByRole("button", { name: "Lưu người dùng", exact: true }).click();
    await expect(dialog.getByRole("status")).toHaveText("Đã cập nhật người dùng.");
    expect((await db.user.findUniqueOrThrow({ where: { id: students[0].id } })).name).toBe(`${tag} Student 0`);
    expect((await db.user.findUniqueOrThrow({ where: { id: students[0].id } })).phone).toBe("");
    page.once("dialog", d => d.accept());
    await dialog.getByRole("button", { name: "Khóa tài khoản", exact: true }).click();
    await expect(dialog.getByRole("status").filter({hasText:"Đã khóa tài khoản."})).toBeVisible();
    expect((await db.user.findUniqueOrThrow({ where: { id: students[0].id } })).active).toBe(false);
    page.once("dialog", d => d.accept());
    await dialog.getByRole("button", { name: "Mở khóa", exact: true }).click();
    await expect(dialog.getByRole("status").filter({hasText:"Đã mở khóa tài khoản."})).toBeVisible();
    page.once("dialog", d => d.accept());
    await dialog.getByRole("button", { name: "Xóa người dùng", exact: true }).click();
    await expect(page.locator("main tbody tr")).toHaveCount(0);
    expect(await db.user.findUnique({ where: { id: students[0].id } })).toBeNull();
    await page.goto(`/admin/users?q=${students[1].email}`);
    await page.getByRole("button", { name: "Sửa nhanh", exact: true }).click();
    page.once("dialog", d => d.accept());
    await page.getByRole("dialog").getByRole("button", { name: "Xóa người dùng", exact: true }).click();
    await expect(page.getByRole("dialog").getByRole("status").filter({hasText:/Tài khoản có lịch sử/})).toBeVisible();
    expect(await db.surveyParticipation.count({ where: { studentId: students[1].student!.id } })).toBe(1);
    await page.goto("/admin/academic");
    const create = page.locator("section.card").filter({ has: page.getByRole("heading", { name: "Thêm khoa", exact: true }) });
    await create.getByLabel("Mã khoa", { exact: true }).fill(`${tag}-EMPTY`);
    await create.getByLabel("Tên khoa", { exact: true }).fill(`${tag} Khoa trống`);
    await create.getByRole("button", { name: "Tạo khoa", exact: true }).click();
    await expect(create.getByRole("status")).toHaveText("Đã tạo khoa.");
    await page.goto("/admin/users");
    await expect(page.getByRole("combobox", { name: "Lọc theo khoa", exact: true }).getByRole("option", { name: `${tag} Khoa trống`, exact: true })).toHaveCount(1);
    await page.goto("/admin/academic");
    let row = page.locator("section.question").filter({ has: page.getByRole("heading", { name: `${tag} Khoa trống`, exact: true }) });
    await row.getByRole("button", { name: "Sửa nhanh", exact: true }).click();
    dialog = page.getByRole("dialog");
    await dialog.getByLabel("Tên khoa", { exact: true }).fill(`${tag} Đã sửa`);
    await dialog.getByRole("button", { name: "Lưu khoa", exact: true }).click();
    await expect(dialog.getByRole("status").filter({hasText:"Đã cập nhật khoa."})).toBeVisible();
    page.once("dialog", d => d.accept());
    await dialog.getByRole("button", { name: "Xóa khoa", exact: true }).click();
    await expect(page.getByRole("heading", { name: `${tag} Đã sửa`, exact: true })).toHaveCount(0);
    row = page.locator("section.question").filter({ has: page.getByRole("heading", { name: `${tag} Khoa`, exact: true }) });
    await row.getByRole("button", { name: "Sửa nhanh", exact: true }).click();
    page.once("dialog", d => d.accept());
    await page.getByRole("dialog").getByRole("button", { name: "Xóa khoa", exact: true }).click();
    await expect(page.getByRole("dialog").getByRole("status").filter({hasText:/Khoa còn lớp/})).toBeVisible();
    await db.notification.create({ data: { userId: admin.id, title: `${tag} Tin ban đầu`, body: "Đã có từ trước", href: "/profile" } });
    await page.goto("/profile");
    await expect.poll(async () => (await page.request.get("/api/notifications")).status()).toBe(200);
    await page.getByRole("banner").getByRole("button", { name: /^Thông báo/ }).click();
    await expect(page.getByRole("dialog", { name: "Thông báo nhanh" }).getByRole("heading", { name: `${tag} Tin ban đầu`, exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Đóng thông báo", exact: true }).click();
    await db.notification.create({ data: { userId: admin.id, title: `${tag} Tin mới`, body: "Nội dung thông báo mới", href: "/admin/users" } });
    await page.evaluate(() => window.dispatchEvent(new Event("focus")));
    await expect(page.getByRole("status").filter({ hasText: "Thông báo mới" })).toContainText(`${tag} Tin mới`);
    await page.getByRole("button", { name: "Xem thông báo", exact: true }).click();
    dialog = page.getByRole("dialog", { name: "Thông báo nhanh" });
    await expect(dialog).toBeVisible();
    await expect(page).toHaveURL(/\/profile$/);
    await expect(dialog.getByRole("heading", { name: `${tag} Tin mới`, exact: true })).toBeVisible();
    await expect(dialog.getByText(privateNotice.title)).toHaveCount(0);
    const denied = await page.request.patch("/api/notifications", { data: { id: privateNotice.id } });
    expect(await denied.json()).toEqual({ updated: 0 });
    expect((await db.notification.findUniqueOrThrow({ where: { id: privateNotice.id } })).readAt).toBeNull();
    expect((await page.request.patch("/api/notifications", { headers: { origin: "https://foreign.example.invalid" }, data: { all: true } })).status()).toBe(403);
    await dialog.getByRole("button", { name: "Đánh dấu tất cả đã đọc", exact: true }).click();
    await expect(dialog.getByText("0 thông báo chưa đọc", { exact: true })).toBeVisible();
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: ".playwright-cli/notification-drawer-mobile.png", fullPage: true });
    await page.keyboard.press("Escape"); await expect(dialog).not.toBeVisible();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(`/admin/users?q=${teacher.email}`);
    await page.getByRole("button", { name: "Sửa nhanh", exact: true }).click();
    page.once("dialog", d => d.accept());
    await page.getByRole("dialog").getByRole("button", { name: "Xóa người dùng", exact: true }).click();
    await expect(page.locator("main tbody tr")).toHaveCount(0);
    expect(await db.user.findUnique({ where: { id: teacher.id } })).toBeNull();
  } finally {
    await db.user.updateMany({ where: { id: { in: fixtureUserIds } }, data: { active: false } });
    await db.$disconnect();
  }
});
